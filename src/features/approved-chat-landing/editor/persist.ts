import type { SupabaseClient } from "@supabase/supabase-js";
import { magicPageService } from "../../../services/magic-page.service";
import { pageService } from "../../../services/page.service";
import { profileService } from "../../../services/profile.service";
import type { MagicPageDocumentV1 } from "../../magic-page-editor-production/magic-document";

/**
 * Phase 9 — real persistence for the conversational landing.
 *
 * The conversation already produces a `MagicPageDocumentV1` (Phase 7) and the
 * engine already knows how to open one (Phase 8). What Phase 8 kept in memory is
 * turned into a real `pages` row here, so the productive route
 * (`/pages/$pageId/edit` -> `MagicProductionEditorHost`) reads the very document
 * the conversation generated.
 *
 * Nothing is re-implemented: page creation goes through the canonical non-admin
 * boundary (`createOrResumeInitialLandingPage` -> RPC
 * `create_initial_landing_page`) and the document is written through the existing
 * `magicPageService.saveDraft` (the same call the productive editor autosaves
 * with). No RLS is widened, no `pageId` is invented, and the dead
 * `magicPageService.createPage` INSERT path is deliberately not used.
 */

export interface LandingPersistenceInput {
  supabase: SupabaseClient;
  userId: string;
  document: MagicPageDocumentV1;
  userEmail?: string | null;
  userMetadata?: Record<string, unknown> | null;
}

/**
 * Outcome of a conversational CREATE_PAGE against real persistence.
 *
 * - `created`: the document was written and `pageId` is ready to open.
 * - `existing-draft`: the owner already had a landing WITH a draft. Per the
 *   Phase 9 decision the conversation must NOT overwrite it silently, so nothing
 *   was written and the caller has to confirm first.
 */
export type LandingPersistenceOutcome =
  | { status: "created"; pageId: string }
  | { status: "existing-draft"; pageId: string };

/**
 * A draft counts as "existing work" when the column holds a non-empty object.
 * The RPC always inserts `template_config = NULL`, so an empty column means
 * there is genuinely nothing to replace and confirming would be a lie.
 */
function draftHasContent(templateConfig: unknown): boolean {
  if (templateConfig === null || templateConfig === undefined) return false;
  if (typeof templateConfig !== "object") return false;
  return Object.keys(templateConfig as Record<string, unknown>).length > 0;
}

/**
 * Create (or resume) the owner's real landing and persist the document the
 * conversation generated.
 *
 * Resuming never duplicates: the schema allows exactly one canonical non-catalog
 * page per owner and the RPC serializes concurrent attempts.
 */
export async function createLandingFromConversation(
  input: LandingPersistenceInput,
): Promise<LandingPersistenceOutcome> {
  const { supabase, userId, document, userEmail, userMetadata } = input;

  if (!userId) {
    throw new Error("Debes iniciar sesión para crear tu página.");
  }

  // The RPC resolves `profile_id` server-side from `public.profiles`, so the
  // profile has to exist first (same prerequisite MyProfilePage establishes).
  await profileService.ensurePrimaryProfileForUser(supabase, {
    userId,
    email: userEmail ?? null,
    userMetadata: userMetadata ?? null,
  });

  const { page, resumed } = await pageService.createOrResumeInitialLandingPage(supabase, userId);

  if (resumed && draftHasContent(page.template_config)) {
    return { status: "existing-draft", pageId: page.id };
  }

  await magicPageService.saveDraft(supabase, page.id, userId, document);
  return { status: "created", pageId: page.id };
}

/**
 * Explicit user choice ("Usar este nuevo diseño"): replace the DRAFT of an
 * existing landing with the document generated by the conversation.
 *
 * Only `pages.template_config` is written. The published column is untouched
 * until the user publishes from the real editor, so a published page never
 * changes here.
 */
export async function replaceLandingDraft(
  input: Omit<LandingPersistenceInput, "userEmail" | "userMetadata"> & { pageId: string },
): Promise<{ pageId: string }> {
  const { supabase, userId, pageId, document } = input;
  if (!userId) {
    throw new Error("Debes iniciar sesión para crear tu página.");
  }
  await magicPageService.saveDraft(supabase, pageId, userId, document);
  return { pageId };
}

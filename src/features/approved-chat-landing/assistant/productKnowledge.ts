function knowledgeSection(start: string, end: string): string {
  const from = PRODUCT_KNOWLEDGE.indexOf(start);
  if (from < 0) return "";
  const endAt = end === "__END__" ? PRODUCT_KNOWLEDGE.length : PRODUCT_KNOWLEDGE.indexOf(end, from + start.length);
  return PRODUCT_KNOWLEDGE.slice(from, endAt > from ? endAt : PRODUCT_KNOWLEDGE.length).trim();
}

/**
 * Sends only the product facts relevant to the current turn. The complete
 * audited knowledge remains in the repository, but is not copied into every
 * paid request unnecessarily.
 */
export function productKnowledgeForQuestion(question: string): string {
  const normalized = question.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  const isGreeting = /^(hola|buenas|hey|buenos dias|buenas tardes|buenas noches)\b/.test(normalized.trim());
  const includeCore = true;
  const includeBenefits = !isGreeting && /cripqer|clickker|landing|pagina|perfil|redes|instagram|que hace|que es|beneficio|contact|cliente|profesional|vender|pedido|reserva|cita/.test(normalized);
  const includeWorkflow = /como funciona|funciona|proceso|paso|crear|publicar|editar|editor|personalizar|registro/.test(normalized);
  const includeFeatures = /whatsapp|qr|codigo|escane|metric|visita|clic|enlace|bloque|catalogo|producto|servicio|analitic|reserva|cita|pedido|contact/.test(normalized);
  const includePricing = /gratis|precio|costo|cuanto|plan|pro|pagar|dinero/.test(normalized);
  const includeExamples = /imagen|foto|ejemplo|plantilla|diseno|identidad|peluquer|barber|restaurante|tienda|profesion/.test(normalized);

  const sections: string[] = [];
  if (includeCore) sections.push(knowledgeSection("IDENTIDAD DE CRIPQER", "COMO FUNCIONA"));
  if (includeWorkflow) sections.push(knowledgeSection("COMO FUNCIONA", "BENEFICIOS CONFIRMADOS"));
  if (includeBenefits) sections.push(knowledgeSection("BENEFICIOS CONFIRMADOS", "FUNCIONES Y SERVICIOS QUE PUEDE EXPLICAR"));
  if (includeFeatures) sections.push(knowledgeSection("FUNCIONES Y SERVICIOS QUE PUEDE EXPLICAR", "COMPARACIONES RESPETUOSAS CON OTRAS PLATAFORMAS"));
  if (includeExamples) sections.push(knowledgeSection("IMAGENES Y EJEMPLOS DEL LANDING", "PLANES, GRATUIDAD Y PRECIOS"));
  if (includePricing) sections.push(knowledgeSection("PLANES, GRATUIDAD Y PRECIOS", "LIMITES Y RESPUESTAS QUE DEBE EVITAR"));
  sections.push(knowledgeSection("LIMITES Y RESPUESTAS QUE DEBE EVITAR", "ESTILO COMERCIAL"));
  sections.push(knowledgeSection("ESTILO COMERCIAL", "__END__"));

  return Array.from(new Set(sections.filter(Boolean))).join("\n\n").slice(0, 7200);
}

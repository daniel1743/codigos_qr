export type PowerEditorMessages = (typeof powerEditorMessages)[PowerEditorLocale];
export type PowerEditorMessageKey = keyof PowerEditorMessages;

export function isPowerEditorLocale(value: unknown): value is PowerEditorLocale {
  return value === "es" || value === "en";
}

export function formatBreakpoint(
  locale: PowerEditorLocale,
  breakpoint: "desktop" | "tablet" | "mobile",
): string {
  return powerEditorMessages[locale].options[breakpoint];
}

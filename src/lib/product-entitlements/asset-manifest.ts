/**
 * CRIPQER — PRODUCT ASSET ENTITLEMENT MANIFEST V1
 *
 * Maps REAL Power Editor assets to product classifications (STANDARD | PREMIUM)
 * so the Product Capability Policy Core can gate *new* selection/insertion/
 * application. It is pure, declarative product metadata.
 *
 * Responsibilities:
 *   - Classify every currently implemented block, layout, section preset and
 *     template into STANDARD or PREMIUM, exactly once.
 *   - Map each classification to the capability that authorizes NEW insertion:
 *       standard  → standard_blocks / standard_sections / standard_templates /
 *                   basic_layout_selection
 *       premium   → premium_blocks / premium_sections / premium_templates /
 *                   advanced_layout
 *   - Fail closed: an unknown/unclassified asset is `UNKNOWN`, never silently
 *     treated as STANDARD (Free).
 *
 * This manifest does NOT:
 *   - implement UI locks
 *   - modify the Power Editor, renderer, or Billing
 *   - change BioTemplateConfig or renderer behavior
 *   - control RENDERING or STORAGE preservation
 *
 * ASSET ENTITLEMENT CONTROLS SELECTION/INSERTION/APPLICATION, NOT RENDERING.
 * A Free user may still render and preserve a premium asset already present in
 * a canonical config (e.g. generated by Engine V2); they merely cannot newly
 * add/select/apply it.
 *
 * Boundary: the frozen Product Capability Policy Core
 * (`src/lib/product-entitlements/capabilities.ts`) is READ ONLY. This manifest
 * imports only its `ProductCapability` *type* (erased at compile time) so the
 * required capability ids are guaranteed valid without runtime coupling.
 */

import type { ProductCapability } from "./capabilities.ts";

/* ============================================================================
 * 1. CORE TYPES
 * ========================================================================== */

/** Product classification of an asset. */
export type ProductAssetTier = "standard" | "premium";

/** The kind of asset being classified. */
export type ProductAssetKind = "block" | "section" | "template" | "layout";

/** Effective classification result (UNKNOWN = fail closed). */
export type ProductAssetClassification = "STANDARD" | "PREMIUM" | "UNKNOWN";

/** The capability that authorizes NEW selection/insertion/application. */
export type AssetRequiredCapability = ProductCapability;

/** Decision shape for an asset lookup. */
export interface AssetEntitlement {
  readonly classification: ProductAssetClassification;
  readonly requiredCapability: AssetRequiredCapability | null;
}


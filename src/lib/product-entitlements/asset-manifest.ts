/* ============================================================================
 * 7. LOOKUP SETS (runtime fail-closed resolution)
 * ========================================================================== */

const STANDARD_BLOCK_SET: ReadonlySet<string> = new Set<string>(STANDARD_BLOCKS);
const PREMIUM_BLOCK_SET: ReadonlySet<string> = new Set<string>(PREMIUM_BLOCKS);
const STANDARD_LAYOUT_SET: ReadonlySet<string> = new Set<string>(STANDARD_LAYOUTS);
const PREMIUM_LAYOUT_SET: ReadonlySet<string> = new Set<string>(PREMIUM_LAYOUTS);
const STANDARD_SECTION_SET: ReadonlySet<string> = new Set<string>(STANDARD_SECTIONS);
const PREMIUM_SECTION_SET: ReadonlySet<string> = new Set<string>(PREMIUM_SECTIONS);
const STANDARD_TEMPLATE_SET: ReadonlySet<string> = new Set<string>(STANDARD_TEMPLATES);
const PREMIUM_TEMPLATE_SET: ReadonlySet<string> = new Set<string>(PREMIUM_TEMPLATES);

const UNKNOWN: AssetEntitlement = Object.freeze({
  classification: "UNKNOWN",
  requiredCapability: null,
});

function standardEntitlement(
  capability: AssetRequiredCapability,
): AssetEntitlement {
  return { classification: "STANDARD", requiredCapability: capability };
}

function premiumEntitlement(
  capability: AssetRequiredCapability,
): AssetEntitlement {
  return { classification: "PREMIUM", requiredCapability: capability };
}

/* ============================================================================
 * 8. PUBLIC LOOKUP HELPERS (pure, fail-closed)
 * ========================================================================== */

export function getBlockEntitlement(blockId: string): AssetEntitlement {
  if (STANDARD_BLOCK_SET.has(blockId)) {
    return standardEntitlement(REQUIRED_CAPABILITY.standardBlock);
  }
  if (PREMIUM_BLOCK_SET.has(blockId)) {
    return premiumEntitlement(REQUIRED_CAPABILITY.premiumBlock);
  }
  return UNKNOWN;
}

export function getSectionEntitlement(sectionId: string): AssetEntitlement {
  if (STANDARD_SECTION_SET.has(sectionId)) {
    return standardEntitlement(REQUIRED_CAPABILITY.standardSection);
  }
  if (PREMIUM_SECTION_SET.has(sectionId)) {
    return premiumEntitlement(REQUIRED_CAPABILITY.premiumSection);
  }
  return UNKNOWN;
}

export function getTemplateEntitlement(templateId: string): AssetEntitlement {
  if (STANDARD_TEMPLATE_SET.has(templateId)) {
    return standardEntitlement(REQUIRED_CAPABILITY.standardTemplate);
  }
  if (PREMIUM_TEMPLATE_SET.has(templateId)) {
    return premiumEntitlement(REQUIRED_CAPABILITY.premiumTemplate);
  }
  return UNKNOWN;
}

export function getLayoutEntitlement(layoutId: string): AssetEntitlement {
  if (STANDARD_LAYOUT_SET.has(layoutId)) {
    return standardEntitlement(REQUIRED_CAPABILITY.standardLayout);
  }
  if (PREMIUM_LAYOUT_SET.has(layoutId)) {
    return premiumEntitlement(REQUIRED_CAPABILITY.premiumLayout);
  }
  return UNKNOWN;
}

/** Generic resolver: (kind, assetId) → AssetEntitlement. */
export function resolveAssetEntitlement(
  kind: ProductAssetKind,
  assetId: string,
): AssetEntitlement {
  switch (kind) {
    case "block":
      return getBlockEntitlement(assetId);
    case "section":
      return getSectionEntitlement(assetId);
    case "template":
      return getTemplateEntitlement(assetId);
    case "layout":
      return getLayoutEntitlement(assetId);
  }
}


